*=====================================================================
*
*  PROGRAM..: COPYFB
*  LANGUAGE.: HLASM - HIGH LEVEL ASSEMBLER FOR Z/OS
*
*  PURPOSE..: SEQUENTIALLY READ THE DATA SET ALLOCATED TO DDNAME
*             INFILE (RECFM=FB, LRECL=80) AND WRITE EVERY RECORD
*             READ TO THE DATA SET ALLOCATED TO DDNAME OUTFILE,
*             WHICH USES THE SAME DCB AS THE INPUT (RECFM=FB,
*             LRECL=80).
*
*  ACCESS...: QSAM (QUEUED SEQUENTIAL ACCESS METHOD), USING THE
*             DCB, OPEN, GET, PUT AND CLOSE MACROS IN MOVE MODE
*             (GM/PM).
*
*  DDNAMES..: INFILE  - INPUT DATA SET   (INPUT)
*             OUTFILE - OUTPUT DATA SET  (OUTPUT)
*
*  RETURN...: RC = 00 - NORMAL COMPLETION
*             RC = 16 - OPEN FAILED FOR INFILE OR OUTFILE
*
*  MESSAGE..: AT THE END A WTO IS ISSUED WITH THE NUMBER OF
*             RECORDS COPIED (SHOWN IN THE JOBLOG / JESMSGLG).
*
*  REGISTERS USED:
*             R2  - POINTER TO THE DCB (OPEN CHECK)
*             R5  - COUNTER OF RECORDS COPIED
*             R11 - WORK REGISTER FOR SAVE AREA CHAINING
*             R12 - PROGRAM BASE REGISTER
*             R13 - ADDRESS OF THIS PROGRAM'S SAVE AREA
*             R14 - RETURN ADDRESS TO THE CALLER
*             R15 - ENTRY POINT ADDRESS / RETURN CODE
*
*  ATTRIBUTES: AMODE 31 / RMODE 24 (QSAM DCBS MUST RESIDE BELOW
*             THE 16MB LINE). NOT REENTRANT (THE DCBS AND THE SAVE
*             AREA ARE INSIDE THE LOAD MODULE ITSELF).
*
*=====================================================================
COPYFB   CSECT                    Start of control section COPYFB
COPYFB   AMODE 31                 Run in 31-bit addressing mode
COPYFB   RMODE 24                 Load below the 16MB line
*
*---------------------------------------------------------------------
*  LINKAGE CONVENTION (ENTRY) - SAVE THE CALLER'S REGISTERS,
*  ESTABLISH THE BASE REGISTER AND CHAIN THE SAVE AREAS.
*---------------------------------------------------------------------
         STM   R14,R12,12(R13)    Save R14-R12 in caller's save area
         LR    R12,R15            R12 gets the entry point address
         USING COPYFB,R12         R12 becomes the base register
         LA    R11,SAVEAREA       R11 points to our save area
         ST    R13,4(,R11)        Our SA points back to caller's SA
         ST    R11,8(,R13)        Caller's SA points forward to ours
         LR    R13,R11            R13 points to our save area
*
*---------------------------------------------------------------------
*  RECORD COUNTER INITIALIZATION
*---------------------------------------------------------------------
         SR    R5,R5              Clear the record counter (R5)
*
*---------------------------------------------------------------------
*  OPEN THE DATA SETS
*  THE OPEN MACRO OPENS DCB INFILE FOR READING (INPUT) AND DCB
*  OUTFILE FOR WRITING (OUTPUT). ATTRIBUTES NOT CODED IN THE DCB
*  (E.G. BLKSIZE) ARE TAKEN FROM THE JCL OR FROM THE DATA SET LABEL.
*---------------------------------------------------------------------
         OPEN  (INFILE,(INPUT),OUTFILE,(OUTPUT))
*
*---------------------------------------------------------------------
*  CHECK THAT BOTH DCBS WERE ACTUALLY OPENED.
*  BIT DCBOFOPN OF FIELD DCBOFLGS IS TURNED ON WHEN OPEN SUCCEEDS.
*  THE FIELDS ARE MAPPED BY THE IHADCB DSECT (GENERATED BY THE
*  DCBD MACRO AT THE END OF THE PROGRAM).
*---------------------------------------------------------------------
         LA    R2,INFILE          R2 gets the address of DCB INFILE
         USING IHADCB,R2          Map the DCB with the IHADCB DSECT
         TM    DCBOFLGS,DCBOFOPN  Test the "DCB is open" bit
         BZ    OPENERR            Bit off: OPEN failed
         LA    R2,OUTFILE         R2 gets the address of DCB OUTFILE
         TM    DCBOFLGS,DCBOFOPN  Test the "DCB is open" bit
         BZ    OPENERR            Bit off: OPEN failed
         DROP  R2                 End the mapping through R2
*
*---------------------------------------------------------------------
*  MAIN LOOP: READ ONE RECORD FROM INFILE AND WRITE IT TO OUTFILE.
*  IN MOVE MODE (MACRF=GM/PM) QSAM MOVES THE RECORD INTO THE GIVEN
*  WORK AREA (RECORD) AND, ON PUT, FROM THE WORK AREA TO THE BUFFER.
*  WHEN THERE ARE NO MORE RECORDS, QSAM AUTOMATICALLY BRANCHES TO
*  THE ROUTINE NAMED IN THE EODAD PARAMETER OF THE DCB (EOFRTN).
*  NOTE: GET/PUT CHANGE R0, R1, R14 AND R15 - THAT IS WHY THE
*  COUNTER IS KEPT IN R5.
*---------------------------------------------------------------------
READLOOP DS    0H                 Start of the read loop
         GET   INFILE,RECORD      Read the next record into RECORD
         AHI   R5,1               Add 1 to the record counter
         PUT   OUTFILE,RECORD     Write the contents of RECORD
         B     READLOOP           Go back and read the next record
*
*---------------------------------------------------------------------
*  END OF FILE (EODAD): CLOSE THE DATA SETS, DISPLAY THE NUMBER OF
*  RECORDS COPIED AND END WITH RC=0.
*---------------------------------------------------------------------
EOFRTN   DS    0H                 QSAM branches here at end of INFILE
         CLOSE (INFILE,,OUTFILE)  Close both (flushes last buffer)
         CVD   R5,DWORK           Convert counter to packed decimal
         UNPK  WTOCNT,DWORK       Unpack to zoned decimal (9 digits)
         OI    WTOCNT+L'WTOCNT-1,X'F0'  Fix the sign of the last digit
         WTO   MF=(E,WTOMSG)      Display the message with the total
         SR    R15,R15            Return code = 0 (success)
         B     EXITPGM            Branch to the exit routine
*
*---------------------------------------------------------------------
*  OPEN ERROR: CLOSE WHATEVER IS OPEN (CLOSE IGNORES A DCB THAT IS
*  NOT OPEN), ISSUE A MESSAGE AND END WITH RC=16.
*---------------------------------------------------------------------
OPENERR  DS    0H                 OPEN error handling routine
         CLOSE (INFILE,,OUTFILE)  Close any DCB that is open
         WTO   'COPYFB - OPEN FAILED FOR INFILE OR OUTFILE'
         LA    R15,16             Return code = 16 (severe error)
*
*---------------------------------------------------------------------
*  LINKAGE CONVENTION (EXIT) - RESTORE THE CALLER'S REGISTERS AND
*  RETURN CONTROL WITH THE RETURN CODE IN R15.
*---------------------------------------------------------------------
EXITPGM  DS    0H                 Single exit point of the program
         L     R13,4(,R13)        R13 points back to caller's SA
         L     R14,12(,R13)       Restore the return address
         LM    R0,R12,20(R13)     Restore R0-R12 (R15 keeps the RC)
         BR    R14                Return control to the caller
*
*=====================================================================
*  DATA AREA
*=====================================================================
SAVEAREA DS    18F                This program's save area (72 bytes)
DWORK    DS    D                  Work area for CVD (8 bytes)
RECORD   DS    CL80               Record read / written work area
*
*---------------------------------------------------------------------
*  WTO MESSAGE IN LIST FORMAT (MF=L) BUILT MANUALLY:
*  +0 LENGTH (2 BYTES) / +2 MCS FLAGS (2 BYTES) / +4 TEXT
*---------------------------------------------------------------------
WTOMSG   DS    0F                 Align the WTO list on a fullword
         DC    AL2(WTOEND-WTOMSG) Total length: header + text
         DC    XL2'0000'          MCS flags (no special options)
         DC    C'COPYFB - RECORDS COPIED: '  Fixed text
WTOCNT   DC    CL9' '             Number of records (zoned decimal)
WTOEND   EQU   *                  Marks the end of the message
*
*---------------------------------------------------------------------
*  DCB FOR THE INPUT DATA SET (DDNAME INFILE)
*---------------------------------------------------------------------
INFILE   DCB   DDNAME=INFILE,      DD name in the JCL                  X
               DSORG=PS,           Physical sequential organiz.        X
               MACRF=GM,           GET in move mode                    X
               RECFM=FB,           Fixed blocked records               X
               LRECL=80,           Record length: 80 bytes             X
               EODAD=EOFRTN        Routine run at end of file
*
*---------------------------------------------------------------------
*  DCB FOR THE OUTPUT DATA SET (DDNAME OUTFILE) - SAME DCB AS INPUT.
*  BLKSIZE IS NOT CODED: IT COMES FROM THE JCL OR IS CALCULATED BY
*  THE SYSTEM (SYSTEM DETERMINED BLOCKSIZE) WHEN BLKSIZE=0.
*---------------------------------------------------------------------
OUTFILE  DCB   DDNAME=OUTFILE,     DD name in the JCL                  X
               DSORG=PS,           Physical sequential organiz.        X
               MACRF=PM,           PUT in move mode                    X
               RECFM=FB,           Fixed blocked records               X
               LRECL=80            Record length: 80 bytes
*
*---------------------------------------------------------------------
*  LITERAL POOL
*---------------------------------------------------------------------
         LTORG                    Literals generated by the macros
*
*---------------------------------------------------------------------
*  GENERAL PURPOSE REGISTER EQUATES
*---------------------------------------------------------------------
R0       EQU   0                  General purpose register 0
R1       EQU   1                  General purpose register 1
R2       EQU   2                  General purpose register 2
R3       EQU   3                  General purpose register 3
R4       EQU   4                  General purpose register 4
R5       EQU   5                  General purpose register 5
R6       EQU   6                  General purpose register 6
R7       EQU   7                  General purpose register 7
R8       EQU   8                  General purpose register 8
R9       EQU   9                  General purpose register 9
R10      EQU   10                 General purpose register 10
R11      EQU   11                 General purpose register 11
R12      EQU   12                 General purpose register 12
R13      EQU   13                 General purpose register 13
R14      EQU   14                 General purpose register 14
R15      EQU   15                 General purpose register 15
*
*---------------------------------------------------------------------
*  IHADCB DSECT - MAPS THE DCB FIELDS (DCBOFLGS, ETC.).
*  IT MUST BE AT THE END BECAUSE IT GENERATES A DSECT (NO STORAGE).
*---------------------------------------------------------------------
         DCBD  DSORG=PS,DEVD=DA   Generate the IHADCB DSECT for PS
*
         END   COPYFB             End of source; entry point
